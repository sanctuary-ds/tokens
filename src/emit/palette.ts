// Emits the palette as an ES module of named exports, and the types that describe it.

/** The resolved palette: what palette.json holds and what the module exports. */
export interface PaletteData {
  defaultFlavor: string;
  defaultGlazing: string;
  defaultWindow: string;
  flavors: Record<string, { scheme: string; colors: Record<string, unknown>; [key: string]: unknown }>;
  pigments: Record<string, { tones: Record<string, string>; [key: string]: unknown }>;
  windows: Record<string, unknown>;
  windowModes: Record<string, unknown>;
  glazings: Record<string, unknown>;
  fonts: Record<string, unknown>;
}

const HEADER = '// Sanctuary palette. Generated by scripts/build.ts; do not edit by hand.\n';

/** A union of string literals, in the order given. */
const union = (values: string[]) => values.map((value) => JSON.stringify(value)).join(' | ');

/**
 * One compact `export const` per top-level key, so a bundler keeps only the keys a consumer
 * imports. palette.json is the readable copy of the same data.
 */
export function emitPaletteModule(data: PaletteData): string {
  const exports = Object.entries(data).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};\n`);
  return `${HEADER}${exports.join('')}`;
}

/** The ids come from the data; a packed-package test fails if this shape stops matching it. */
export function emitPaletteTypes(data: PaletteData): string {
  const flavors = Object.values(data.flavors);
  const pigments = Object.values(data.pigments);
  return `${HEADER}
export type FlavorId = ${union(Object.keys(data.flavors))};
export type PigmentId = ${union(Object.keys(data.pigments))};
export type WindowId = ${union(Object.keys(data.windows))};
export type WindowModeId = ${union(Object.keys(data.windowModes))};
export type GlazingId = ${union(Object.keys(data.glazings))};
export type FontRole = ${union(Object.keys(data.fonts))};
/** A color of a flavor, named as its custom property without \`--san-\`. */
export type ColorName = ${union(Object.keys(flavors[0].colors))};
export type Tone = ${Object.keys(pigments[0].tones).join(' | ')};
export type Scheme = ${union([...new Set(flavors.map((flavor) => flavor.scheme))].sort())};

export interface Color {
  hex: string;
  /** Lightness, chroma and hue. */
  oklch: [number, number, number];
  alpha?: number;
}

export interface Flavor {
  name: string;
  hour: string;
  scheme: Scheme;
  blurb: string;
  accent: PigmentId;
  colors: Record<ColorName, Color>;
}

export interface Pigment {
  hue: number;
  chroma: number;
  drift?: number;
  note: string;
  tones: Record<Tone, string>;
}

export interface PaletteWindow {
  name: string;
  stops: PigmentId[];
  note: string;
}

export interface WindowMode {
  name: string;
  source: string;
  note: string;
}

export interface Glazing {
  name: string;
  note: string;
}

export interface Font {
  family: string;
  fallbacks: string[];
  generic: string;
  weights: number[];
  styles: string[];
}

export declare const defaultFlavor: FlavorId;
export declare const defaultGlazing: GlazingId;
export declare const defaultWindow: WindowModeId;
export declare const flavors: Record<FlavorId, Flavor>;
export declare const pigments: Record<PigmentId, Pigment>;
export declare const windows: Record<WindowId, PaletteWindow>;
export declare const windowModes: Record<WindowModeId, WindowMode>;
export declare const glazings: Record<GlazingId, Glazing>;
export declare const fonts: Record<FontRole, Font>;
`;
}
